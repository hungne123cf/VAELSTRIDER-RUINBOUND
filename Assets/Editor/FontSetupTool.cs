using System;
using System.IO;
using System.Collections.Generic;
using UnityEditor;
using UnityEngine;
using UnityEngine.TextCore.LowLevel;
using TMPro;

public static class FontSetupTool
{
    [InitializeOnLoadMethod]
    public static void AutoGenerateDreamsUnwoundFont()
    {
        EditorApplication.delayCall += () =>
        {
            GenerateDreamsUnwoundFont();
        };
    }

    [MenuItem("Tools/Fonts/Generate Dreams Unwound Font Asset")]
    public static void GenerateDreamsUnwoundFont()
    {
        try
        {
            string assetPath = "Assets/Resources/Fonts/DreamsUnwound SDF.asset";
            var existing = AssetDatabase.LoadAssetAtPath<TMP_FontAsset>(assetPath);
            if (existing != null)
            {
                // Asset đã tồn tại hoàn hảo, không xóa để bảo toàn GUID và tham chiếu
                if (TMP_Settings.defaultFontAsset != null && TMP_Settings.defaultFontAsset != existing)
                {
                    if (existing.fallbackFontAssetTable == null) existing.fallbackFontAssetTable = new List<TMP_FontAsset>();
                    if (!existing.fallbackFontAssetTable.Contains(TMP_Settings.defaultFontAsset))
                    {
                        existing.fallbackFontAssetTable.Add(TMP_Settings.defaultFontAsset);
                        EditorUtility.SetDirty(existing);
                        AssetDatabase.SaveAssets();
                    }
                }
                return;
            }

            Font dreamsTtf = AssetDatabase.LoadAssetAtPath<Font>("Assets/Resources/Fonts/iCielDreamsUnwound-Regular.ttf");
            if (dreamsTtf == null)
            {
                dreamsTtf = AssetDatabase.LoadAssetAtPath<Font>("Assets/Fonts/Dreams Unwound VH/Dreams Unwound VH/Regular Fonts/iCielDreamsUnwound-Regular.ttf");
            }
            if (dreamsTtf == null) return;

            TMP_FontAsset dreamsSdf = CreateAndSaveFontAsset(dreamsTtf, assetPath, "DreamsUnwound SDF");
            if (dreamsSdf != null)
            {
                if (TMP_Settings.defaultFontAsset != null && TMP_Settings.defaultFontAsset != dreamsSdf)
                {
                    dreamsSdf.fallbackFontAssetTable = new List<TMP_FontAsset> { TMP_Settings.defaultFontAsset };
                }
                EditorUtility.SetDirty(dreamsSdf);
                AssetDatabase.SaveAssets();
                AssetDatabase.Refresh();
                Debug.Log("<color=green>[FontSetupTool] SUCCESS!</color> Dreams Unwound SDF created and configured as primary game font!");
            }
        }
        catch (Exception ex)
        {
            Debug.LogWarning("[FontSetupTool] Dreams Unwound generation note: " + ex.Message);
        }
    }

    [MenuItem("Tools/Fonts/Apply Dreams Unwound To Active Scene")]
    public static void ApplyDreamsUnwoundToActiveScene()
    {
        var dreamsSdf = AssetDatabase.LoadAssetAtPath<TMP_FontAsset>("Assets/Resources/Fonts/DreamsUnwound SDF.asset");
        if (dreamsSdf == null)
        {
            Debug.LogWarning("[FontSetupTool] DreamsUnwound SDF.asset not found.");
            return;
        }

        var tmps = UnityEngine.Object.FindObjectsByType<TextMeshProUGUI>(FindObjectsInactive.Include, FindObjectsSortMode.None);
        int count = 0;
        foreach (var txt in tmps)
        {
            if (txt == null) continue;
            txt.font = dreamsSdf;
            txt.fontSharedMaterial = dreamsSdf.material;
            if (txt.outlineWidth > 0.16f) txt.outlineWidth = 0.12f;
            if (txt.fontSize < 16f) txt.fontSize = Mathf.Max(txt.fontSize * 1.45f, 18f);
            else if (txt.fontSize < 24f) txt.fontSize = Mathf.Min(txt.fontSize * 1.25f, 32f);
            EditorUtility.SetDirty(txt);
            count++;
        }
        UnityEditor.SceneManagement.EditorSceneManager.MarkAllScenesDirty();
        Debug.Log($"<color=green>[FontSetupTool] SUCCESS!</color> Applied Dreams Unwound to {count} TextMeshPro objects in scene!");
    }

    [MenuItem("Tools/Fonts/Generate Dark Fantasy Fonts")]
    public static void GenerateFontAssets()
    {
        try
        {
            Debug.Log("<color=cyan>[FontSetupTool]</color> Generating Dark Fantasy Font Assets with proper Atlas Textures...");

            string resourcesFontsDir = "Assets/Resources/Fonts";
            if (!Directory.Exists(resourcesFontsDir))
            {
                Directory.CreateDirectory(resourcesFontsDir);
                AssetDatabase.Refresh();
            }

            // 1. Load TTF Fonts
            Font cinzelTtf = AssetDatabase.LoadAssetAtPath<Font>("Assets/Resources/Fonts/Cinzel-Variable.ttf");
            Font beVietnamTtf = AssetDatabase.LoadAssetAtPath<Font>("Assets/Resources/Fonts/BeVietnamPro-SemiBold.ttf");

            if (cinzelTtf == null || beVietnamTtf == null)
            {
                Debug.LogWarning("<color=yellow>[FontSetupTool]</color> TTF font files not loaded yet.");
                return;
            }

            string beVietnamAssetPath = "Assets/Resources/Fonts/BeVietnamPro SDF.asset";
            string cinzelAssetPath = "Assets/Resources/Fonts/Cinzel SDF.asset";
            string vaelstriderAssetPath = "Assets/Resources/Fonts/VaelstriderFont.asset";

            // Delete old broken assets if any
            AssetDatabase.DeleteAsset(beVietnamAssetPath);
            AssetDatabase.DeleteAsset(cinzelAssetPath);
            AssetDatabase.DeleteAsset(vaelstriderAssetPath);
            AssetDatabase.Refresh();

            // Create BeVietnamPro
            TMP_FontAsset beVietnamSdf = CreateAndSaveFontAsset(beVietnamTtf, beVietnamAssetPath, "BeVietnamPro SDF");

            // Create Cinzel
            TMP_FontAsset cinzelSdf = CreateAndSaveFontAsset(cinzelTtf, cinzelAssetPath, "Cinzel SDF");

            if (cinzelSdf != null && beVietnamSdf != null)
            {
                // Fallback: Cinzel -> BeVietnamPro
                cinzelSdf.fallbackFontAssetTable = new List<TMP_FontAsset> { beVietnamSdf };
                EditorUtility.SetDirty(cinzelSdf);

                // Copy BeVietnamPro as VaelstriderFont for backward compatibility
                AssetDatabase.CopyAsset(beVietnamAssetPath, vaelstriderAssetPath);
            }

            AssetDatabase.SaveAssets();
            AssetDatabase.Refresh();

            Debug.Log("<color=green>[FontSetupTool] SUCCESS!</color> Clean Dark Fantasy font assets created without touching engine fallbacks!");
        }
        catch (Exception ex)
        {
            Debug.LogError("[FontSetupTool] Error during font generation: " + ex.Message + "\n" + ex.StackTrace);
        }
    }

    private static TMP_FontAsset CreateAndSaveFontAsset(Font ttfFont, string assetPath, string name)
    {
        TMP_FontAsset fontAsset = TMP_FontAsset.CreateFontAsset(
            ttfFont, 90, 9, GlyphRenderMode.SDFAA, 1024, 1024, AtlasPopulationMode.Dynamic, true
        );
        fontAsset.name = name;

        // 1. Create main asset
        AssetDatabase.CreateAsset(fontAsset, assetPath);

        // 2. Persist all atlas textures as sub-assets
        if (fontAsset.atlasTextures != null)
        {
            for (int i = 0; i < fontAsset.atlasTextures.Length; i++)
            {
                var tex = fontAsset.atlasTextures[i];
                if (tex != null)
                {
                    tex.name = name + " Atlas " + i;
                    AssetDatabase.AddObjectToAsset(tex, fontAsset);
                }
            }
        }

        // 3. Persist Material as sub-asset with valid _MainTex texture binding
        if (fontAsset.material != null)
        {
            fontAsset.material.name = name + " Material";
            if (fontAsset.atlasTextures != null && fontAsset.atlasTextures.Length > 0 && fontAsset.atlasTextures[0] != null)
            {
                fontAsset.material.SetTexture(ShaderUtilities.ID_MainTex, fontAsset.atlasTextures[0]);
            }
            AssetDatabase.AddObjectToAsset(fontAsset.material, fontAsset);
        }

        EditorUtility.SetDirty(fontAsset);
        return fontAsset;
    }
}
